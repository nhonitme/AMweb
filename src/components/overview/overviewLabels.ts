let currentTranslate: (key: string, fallback?: string) => string = (_key, fallback) => fallback ?? _key

export function setOverviewTranslator(
  translate: (key: string, fallback?: string) => string,
): void {
  currentTranslate = translate
}

export function overviewLabel(
  translate: ((key: string, fallback?: string) => string) | undefined,
  text: string,
): string {
  const key = OVERVIEW_TEXT_KEYS[text]
  if (key) return translate ? translate(key, text) : text
  if (text.startsWith(TAX_CIT_PREFIX)) {
    const quarter = text.slice(TAX_CIT_PREFIX.length)
    const template = translate ? translate("DASH_TAX_CIT_Q", "Thuế TNDN tạm tính Q{0}") : "Thuế TNDN tạm tính Q{0}"
    return template.replaceAll("{0}", quarter)
  }
  return text
}

export function translateOverviewText(value: string): string {
  if (typeof value !== "string") return value
  return overviewLabel(currentTranslate, value)
}
