function isDraftReady(record: ChitInfo): boolean {
  const details = getActiveChitDetails(record.DETAILS)
  return Boolean(normalizeYmd(record.CHIT_YMD))
    && details.length > 0
    && details.every((detail) => Boolean(String(detail.DEBIT ?? "").trim() && String(detail.CREDIT ?? "").trim()))
}

function getDraftStatus(draft: VatBatchDraft): string {
  if (draft.error) return "Có lỗi"
  if (draft.savedChitCd && draft.linkedInvoiceKeys.length === draft.invoices.length) {
    const hasCogsRows = getDraftCogsLines(draft).length > 0
    return !hasCogsRows || draft.cogsLinked
      ? "Đã lưu"
      : "Chờ lưu nghiệp vụ giá vốn"
  }
  if (draft.savedChitCd) return "Chờ liên kết"
  return isDraftReady(draft.record) ? "Sẵn sàng" : "Cần hoàn thiện hạch toán"
}

