function getSequenceResetKey(resetType: string, value: unknown): string {
  const date = normalizeYmd(value as Date | string | null)
  if (!date) return ""
  if (resetType === "YEAR") return String(date.getFullYear())
  if (resetType === "MONTH") return `${date.getFullYear()}${String(date.getMonth() + 1).padStart(2, "0")}`
  return ""
}

function formatVoucherSequenceCode(preview: SysCodeSequencePreview, number: number, value: unknown): string {
  const date = normalizeYmd(value as Date | string | null) ?? new Date()
  const numberLength = Number(preview.NUMBER_LENGTH) > 0 ? Number(preview.NUMBER_LENGTH) : 6
  const replacements: Record<string, string> = {
    PREFIX: String(preview.PREFIX ?? ""),
    SUFFIX: String(preview.SUFFIX ?? ""),
    YYYY: String(date.getFullYear()),
    YY: String(date.getFullYear()).slice(-2),
    MM: String(date.getMonth() + 1).padStart(2, "0"),
    DD: String(date.getDate()).padStart(2, "0"),
    NO: String(number).padStart(numberLength, "0"),
  }
  const configuredPattern = String(preview.CODE_PATTERN ?? "").trim()
  const pattern = configuredPattern && /\{NO\}/i.test(configuredPattern)
    ? configuredPattern
    : "{PREFIX}{NO}{SUFFIX}"

  return pattern.replace(/\{(PREFIX|SUFFIX|YYYY|YY|MM|DD|NO)\}/gi, (_token, name: string) => replacements[name.toUpperCase()] ?? "")
}

function buildDraftSequenceCodes(preview: SysCodeSequencePreview, drafts: VatBatchDraft[]): Map<string, string> {
  const unsavedDrafts = drafts.filter((draft) => !draft.savedChitCd)
  const resetType = String(preview.RESET_TYPE ?? "NONE").trim().toUpperCase()
  let currentNumber = Math.max(0, Number(preview.NEXT_NO ?? 1) - 1)
  let currentResetKey = String(preview.RESET_KEY ?? "")
  const result = new Map<string, string>()

  unsavedDrafts.forEach((draft) => {
    const date = draft.record.CHIT_YMD
    const expectedResetKey = getSequenceResetKey(resetType, date)
    if (resetType !== "NONE" && expectedResetKey !== currentResetKey) {
      currentNumber = 0
    }
    currentNumber += 1
    currentResetKey = expectedResetKey
    result.set(draft.key, formatVoucherSequenceCode(preview, currentNumber, date))
  })

  return result
}

function getDraftCogsLines(draft: VatBatchDraft) {
  return getActiveChitDetails(draft.cogsDetails).filter((line) => Boolean(
    String(line.DEBIT ?? "").trim() || String(line.CREDIT ?? "").trim()
      || String(line.DETAIL_DESCRIPTION_VIET ?? "").trim() || Number(line.AMOUNT ?? 0),
  ))
}

function isCogsLineComplete(line: ChitDetail): boolean {
  return Boolean(String(line.DEBIT ?? "").trim() && String(line.CREDIT ?? "").trim() && Number(line.AMOUNT ?? 0) > 0)
}

function normalizeInventoryMatchText(value: unknown): string {
  return String(value ?? "").trim().toLocaleLowerCase().replace(/\s+/g, " ")
}

function toInventoryNumber(value: unknown): number {
  const parsed = typeof value === "number" ? value : Number(String(value ?? "").replace(/,/g, ""))
  return Number.isFinite(parsed) ? parsed : 0
}

function findMatchingProduct(row: VatInvoiceInventoryJsonRow, products: Product[]): Product | null {
  const name = normalizeInventoryMatchText(row.name)
  const unit = normalizeInventoryMatchText(row.unit)
  if (!name || !unit) return null
  const matches = products.filter((product) =>
    normalizeInventoryMatchText(product.PRODUCT_NM_VIET) === name
    && [product.UNIT_CD, product.UNIT_NM].some((value) => normalizeInventoryMatchText(value) === unit),
  )
  return matches.length === 1 ? matches[0] : null
}

function productUnitMatches(row: VatInvoiceInventoryJsonRow, product: Product): boolean {
  const unit = normalizeInventoryMatchText(row.unit)
  return Boolean(unit && [product.UNIT_CD, product.UNIT_NM].some((value) => normalizeInventoryMatchText(value) === unit))
}

function buildInventoryOutputLine(
  row: VatInvoiceInventoryJsonRow,
  mapping: VatInvoiceInventoryMapping,
  companyCd: string,
  date: ChitInfo["CHIT_YMD"],
  currency: string,
  exchangeRate: number,
  sort: number,
): InventoryOutputLine {
  const base = createDefaultInventoryOutputLine(companyCd, date, sort)
  const product = mapping.product!
  const store = mapping.store!
  const quantity = toInventoryNumber(row.quantity)
  const revenueAmountFc = toInventoryNumber(row.amount) || quantity * toInventoryNumber(row.unitPrice)
  const rate = currency.toUpperCase() === "VND" ? 1 : exchangeRate || 1
  return {
    ...base,
    PRODUCT_ID: product.PRODUCT_ID,
    PRODUCT_CD: product.PRODUCT_CD,
    PRODUCT_NM_VIET: product.PRODUCT_NM_VIET,
    PRODUCT_NM_ENG: product.PRODUCT_NM_ENG,
    PRODUCT_NM_KOR: product.PRODUCT_NM_KOR,
    PRODUCT_NM_CHINA: product.PRODUCT_NM_CHINA,
    STORE_ID: store.STORE_ID,
    STORE_CD: store.STORE_CD,
    STORE_NM_VIET: store.STORE_NM_VIET,
    STORE_NM_ENG: store.STORE_NM_ENG,
    STORE_NM_KOR: store.STORE_NM_KOR,
    STORE_NM_CHINA: store.STORE_NM_CHINA,
    UNIT_ID: product.UNIT_ID ?? null,
    UNIT_CD: product.UNIT_CD ?? "",
    UNIT_NM_VIET: product.UNIT_NM ?? "",
    QUANTITY: quantity,
    UNIT_PRICE_CC: 0,
    AMOUNT_CC: 0,
    REVENUE_UNIT_PRICE_CC: toInventoryNumber(row.unitPrice) * rate,
    REVENUE_AMOUNT_CC: revenueAmountFc * rate,
    FC_TYPE: currency || "VND",
    UNIT_PRICE_FC: 0,
    REVENUE_UNIT_PRICE_FC: toInventoryNumber(row.unitPrice),
    AMOUNT_FC: 0,
    REVENUE_AMOUNT_FC: revenueAmountFc,
    EXCHANGE_RATES: rate,
    SUMMARY: String(row.name ?? "").trim(),
    INVENTORY_YMD: date,
    OUTPUT_INVENTORY_YMD: date,
    SORT: sort,
  }
}

